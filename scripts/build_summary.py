"""Build evidence/results/summary-data.md: per-experiment tables computed only from evidence/results/*.json.
(The hand-written evidence/results/summary.md cites these numbers.)"""
import glob
import json
import os
import statistics
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "evidence" / "results"


def load(pat):
    out = []
    for f in sorted(glob.glob(str(R / pat))):
        if "INVALID" in f:
            continue
        out.append((os.path.basename(f)[:-5], json.load(open(f, encoding="utf-8"))))
    return out


def fmt(x):
    return "-" if x is None else str(x)


L = ["# Per-run data (generated by scripts/build_summary.py from evidence/results/*.json)", ""]

L += ["## E1 replica failure (probe 8 req/s GET /api/accounts, window = injection -> recovery + 15 s)", "",
      "| run | requests | failed | availability % | avg ms | p95 ms | max ms | endpoint drop s | first fail s | recovery s | user-visible outage s | alerts |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for n, r in load("e1-*.json"):
    s = r["stats_after_injection"]
    al = "; ".join(f"{k}: pending {v['pending_s']} s, firing {v['firing_s']}" for k, v in r["alerts"].items()) or "none"
    L.append(f"| {n} | {s['requests']} | {s['failed']} | {s['availability_pct']} | {s['lat_avg_ms']} | {s['lat_p95_ms']} | "
             f"{s['lat_max_ms']} | {fmt(r['detection']['endpoint_drop_s'])} | {fmt(r['detection']['first_failed_request_s'])} | "
             f"{fmt(r['recovery']['recovery_s'])} | {r['recovery']['user_visible_outage_s']} | {al} |")

L += ["", "## E2 database outage (20 s; both configs probed at once, 6 req/s each, timeout 12 s; writer with client_id retries)", "",
      "| run | config | req during outage | failed | avg ms | p95 ms | codes | first fail s | last fail ends s | recovery after restore cmd s | writes acked / rows / distinct / balance ok |",
      "|---|---|---|---|---|---|---|---|---|---|---|"]
for n, r in load("e2-*.json"):
    for c, v in r["configs"].items():
        s = v["stats_during_outage"]
        i = v["integrity"]
        L.append(f"| {n} | {c} | {s['requests']} | {s['failed']} | {s['lat_avg_ms']} | {s['lat_p95_ms']} | {s['codes']} | "
                 f"{fmt(v['detection']['first_failed_request_s'])} | {fmt(v['recovery']['last_failed_request_end_s'])} | "
                 f"{fmt(v['recovery']['recovery_after_restore_cmd_s'])} | {i['acknowledged']}/{i['rows_in_db']}/{i['distinct_client_id']}/{i['pass']} |")
    L.append(f"| {n} | alerts | " + "; ".join(f"{k}: pending {v['pending_s']} s, firing {v['firing_s']} s, cleared {v['cleared_s']}"
                                             for k, v in r["alerts"].items()) + " |||||||||")

L += ["", "## E3 load increase (5 -> 30 -> 5 req/s, 5 users)", "",
      "| run | phase | requests | ok | failed | 429 | ok req/s | avg ms | p95 ms | max ms | api CPU m (per pod) | gateway CPU m | postgres CPU m |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for n, r in load("e3-*.json"):
    for ph, s in r["phases"].items():
        res = s["resources"]
        api = ", ".join(str(v["cpu_millicores"]) for k, v in sorted(res.items())
                        if k.startswith("api-baseline" if "baseline" in n else "api-") and ("baseline" in n or "baseline" not in k))
        gw = ", ".join(str(v["cpu_millicores"]) for k, v in sorted(res.items()) if k.startswith("gateway"))
        pg = res.get("postgres-0", {}).get("cpu_millicores")
        L.append(f"| {n} | {ph} | {s['requests']} | {s['success']} | {s['failed']} | {s['excluded']} | {s['achieved_success_rps']} | "
                 f"{s['lat_avg_ms']} | {s['lat_p95_ms']} | {s['lat_max_ms']} | {api} | {gw} | {pg} |")
    L.append(f"| {n} | alerts | {r['alerts'] or 'none'} |||||||||||")

L += ["", "## E4 alerts", ""]
for n, r in load("e4-*.json"):
    if n == "e4-quiet-window":
        L.append(f"- **{n}**: {r['duration_s']} s, {r['polls']} polls, alerts seen: {r['alerts_seen'] or 'none'}; probe {r['probe']['requests']} req, {r['probe']['failed']} failed")
    elif n.startswith("e4-replica"):
        L.append(f"- **{n}** rule `{r['rule']}`: alerts {r['alerts']}; endpoint drop {r['endpoint_drop_s']} s, back {r['endpoints_back_s']} s; "
                 f"restarts {r['container_restarts']}; probe {r['probe_after_injection']['requests']} req, {r['probe_after_injection']['failed']} failed "
                 f"({r['probe_after_injection']['codes']}), max {r['max_latency_ms']} ms")
    else:
        L.append(f"- **{n}** expected {r['expected_alert']}, fired {r['fired']}, correct={r['correct']}; alerts {r['alerts']}; "
                 f"probe during fault {r['probe_fault_window']['requests']} req, {r['probe_fault_window']['failed']} failed, "
                 f"avg {r['probe_fault_window']['lat_avg_ms']} ms, p95 {r['probe_fault_window']['lat_p95_ms']} ms")

for pat, title in (("e5-*.json", "E5 access control"), ("e6-*.json", "E6 input/limits"), ("e8-*.json", "E8 degradation")):
    for n, r in load(pat):
        L += ["", f"## {title} ({n})", "", "| case | status | expected | pass |", "|---|---|---|---|"]
        for c in r["cases"]:
            exp = c["expected"] if isinstance(c["expected"], (int, str)) and not str(c["expected"]).startswith("<function") else "401 or 429"
            L.append(f"| {c['case']} | {c['status']} | {exp} | {c['pass']} |")
        extra = {k: v for k, v in r.items() if k not in ("cases", "login_gateway_log", "experiment")}
        L.append("")
        L.append("```")
        L.append(json.dumps(extra, indent=1, default=str)[:3000])
        L.append("```")

L += ["", "## E7 recovery and consistency (200 creates, client_id retries, one pod deleted mid-run)", "",
      "| run | attempts | attempt codes | final codes | first attempt failed | rows | duplicates | balances ok | avg ms | p95 ms | pass |",
      "|---|---|---|---|---|---|---|---|---|---|---|"]
for n, r in load("e7-*.json"):
    L.append(f"| {n} | {r['attempts']} | {r['attempt_codes']} | {r['final_codes']} | {r['first_attempt_failed']} | {r['rows']} | "
             f"{r['duplicates_db']} | {all(c['pass'] for c in r['checks'])} | {r['lat_avg_ms']} | {r['lat_p95_ms']} | {r['pass']} |")

(R / "summary-data.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
